    t = y * 100 // H
    r = (14 * (100 - t) + 8 * t) // 100
    g = (18 * (100 - t) + 12 * t) // 100
    b = (36 * (100 - t) + 24 * t) // 100
    for x in range(W):
        buf[y][x] = (r, g, b)

