def fill_rect(x, y, w, h, col):
    for j in range(max(0, y), min(H, y + h)):
        for i in range(max(0, x), min(W, x + w)):
            buf[j][i] = col

def draw_border(x, y, w, h, thick, col):
    fill_rect(x, y, w, thick, col)
    fill_rect(x, y + h - thick, w, thick, col)
    fill_rect(x, y, thick, h, col)
    fill_rect(x + w - thick, y, thick, h, col)

def draw_circle(cx, cy, radius, col, fill=True):
    for dy in range(-radius, radius + 1):
        dx_max = int((radius * radius - dy * dy) ** 0.5)
        if fill:
            for dx in range(-dx_max, dx_max + 1):
                if 0 <= cx + dx < W and 0 <= cy + dy < H:
                    buf[cy + dy][cx + dx] = col
        else:
            for dx in (-dx_max, dx_max):
                if 0 <= cx + dx < W and 0 <= cy + dy < H:
                    buf[cy + dy][cx + dx] = col

