def draw_str(x, y, text, col, scale=1):
    cx = x
    for ch in text.upper():
        c = ord(ch)
        if 32 <= c <= 90:
            glyph = font8x8[c - 32]
            for row in range(8):
                bits = glyph[row]
                for col_idx in range(8):
                    if bits & (0x80 >> col_idx):
                        fill_rect(cx + col_idx * scale, y + row * scale, scale, scale, col)
        cx += 8 * scale

def draw_centered_str(cx, y, text, col, scale=1):
    w = len(text) * 8 * scale
    draw_str(cx - w // 2, y, text, col, scale)

# Background gradient
